/** Creates a refresh token for one of SPCL's unattended Gmail senders. */
import { google } from "googleapis";
import dotenv from "dotenv";
import { execFile } from "node:child_process";
import { chmod, readFile, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import path from "node:path";
import process from "node:process";
import { promisify } from "node:util";

const GMAIL_SEND_SCOPE = "https://www.googleapis.com/auth/gmail.send";

const args = process.argv.slice(2);
const reminderProfile = args.includes("--profile=reminders");
const reuseReceiptClient = args.includes("--reuse-receipt-client");
const positional = args.filter((arg) => !arg.startsWith("--"));
const credentialsPath = positional[0];
const outputPath = path.resolve(
  positional[1] || (reminderProfile ? ".env.gmail.reminders" : ".env.gmail"),
);

if (!credentialsPath && !reuseReceiptClient) {
  console.error(
    "Usage: npm run authorize:gmail -- /path/to/oauth-client.json [/path/to/output.env] [--profile=reminders]\n" +
      "   or: npm run authorize:gmail -- --profile=reminders --reuse-receipt-client",
  );
  process.exit(2);
}

const installed = reuseReceiptClient
  ? await loadReceiptOAuthClient()
  : JSON.parse(await readFile(path.resolve(credentialsPath!), "utf8")).installed;

if (!installed?.client_id || !installed?.client_secret) {
  throw new Error("Choose Desktop app when creating the OAuth client, then use its downloaded JSON file.");
}

const callback = await openAuthorizationWindow(
  installed.client_id,
  installed.client_secret,
  reminderProfile ? "notifications@fywycable.com" : undefined,
);
const auth = new google.auth.OAuth2(installed.client_id, installed.client_secret, callback.redirectUri);
const { tokens } = await auth.getToken(callback.code);

if (!tokens.refresh_token) {
  throw new Error(
    "Google did not return a refresh token. Revoke the app's existing access and authorize again.",
  );
}

const prefix = reminderProfile ? "REMINDER_GMAIL" : "GMAIL";
const envFile = [
  "# Generated by npm run authorize:gmail. Keep this file private.",
  `${prefix}_CLIENT_ID=${installed.client_id}`,
  `${prefix}_CLIENT_SECRET=${installed.client_secret}`,
  `${prefix}_REFRESH_TOKEN=${tokens.refresh_token}`,
  `${prefix}_SENDER_ADDRESS=${reminderProfile ? "notifications" : "receipts"}@fywycable.com`,
  `${prefix}_SENDER_NAME=SPCL/FYWY Cable - Do Not Reply`,
  "",
].join("\n");

await writeFile(outputPath, envFile, { encoding: "utf8", mode: 0o600 });
await chmod(outputPath, 0o600);

console.log(`Gmail authorization saved securely to ${outputPath}`);
console.log("Do not commit, paste, or send that file. Copy its values into the NAS .env.production file.");

async function loadReceiptOAuthClient() {
  const receiptEnvPath = path.resolve(".env.gmail");
  const receiptEnv = dotenv.parse(await readFile(receiptEnvPath, "utf8"));
  const clientId = receiptEnv.GMAIL_CLIENT_ID?.trim();
  const clientSecret = receiptEnv.GMAIL_CLIENT_SECRET?.trim();
  if (!clientId || !clientSecret) {
    throw new Error(`${receiptEnvPath} does not contain the existing Gmail OAuth client.`);
  }
  return { client_id: clientId, client_secret: clientSecret };
}

async function openAuthorizationWindow(
  clientId: string,
  clientSecret: string,
  loginHint?: string,
) {
  let resolveCode: ((code: string) => void) | undefined;
  let rejectCode: ((error: Error) => void) | undefined;
  const codePromise = new Promise<string>((resolve, reject) => {
    resolveCode = resolve;
    rejectCode = reject;
  });

  const server = createServer((request, response) => {
    const requestUrl = new URL(request.url || "/", "http://127.0.0.1");
    const error = requestUrl.searchParams.get("error");
    const code = requestUrl.searchParams.get("code");

    response.setHeader("Content-Type", "text/html; charset=utf-8");
    if (error || !code) {
      response.end("<h1>Gmail authorization failed</h1><p>You may close this window.</p>");
      rejectCode?.(new Error(error || "Google did not return an authorization code."));
      return;
    }

    response.end("<h1>SPCL Gmail authorization complete</h1><p>You may close this window and return to the terminal.</p>");
    resolveCode?.(code);
  });

  await new Promise<void>((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", resolve);
  });

  const address = server.address();
  if (!address || typeof address === "string") {
    server.close();
    throw new Error("Could not open a local OAuth callback port.");
  }

  const redirectUri = `http://127.0.0.1:${address.port}`;
  const oauth = new google.auth.OAuth2(clientId, clientSecret, redirectUri);
  const authorizationUrl = oauth.generateAuthUrl({
    access_type: "offline",
    prompt: "consent",
    scope: [GMAIL_SEND_SCOPE],
    login_hint: loginHint,
  });

  console.log("Opening Google authorization in your browser...");
  try {
    const openCommand = process.platform === "darwin" ? "open" : "xdg-open";
    await promisify(execFile)(openCommand, [authorizationUrl]);
  } catch {
    console.log(`Open this URL in a browser on this computer:\n${authorizationUrl}`);
  }

  try {
    const code = await codePromise;
    return { code, redirectUri };
  } finally {
    server.close();
  }
}
